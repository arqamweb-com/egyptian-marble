                <script>
                    (function() {
                        var root = document.querySelector('.eml-steps-carousel');
                        if (!root) return;

                        var track = root.querySelector('.eml-steps-track');
                        var dotsWrap = root.querySelector('.eml-steps-dots');
                        var prevBtn = root.querySelector('.eml-steps-prev');
                        var nextBtn = root.querySelector('.eml-steps-next');
                        var originals = Array.prototype.slice.call(root.querySelectorAll('.eml-steps-slide'));
                        if (!track || !originals.length) return;

                        var count = originals.length;
                        var index = 0;
                        var timer = null;
                        var busy = false;

                        // Clone the full set once so the loop never shows an empty edge.
                        originals.forEach(function(slide) {
                            var clone = slide.cloneNode(true);
                            clone.setAttribute('aria-hidden', 'true');
                            clone.removeAttribute('aria-label');
                            track.appendChild(clone);
                        });

                        var all = Array.prototype.slice.call(track.children);
                        var base = all[0].offsetLeft;

                        function move(i, animate) {
                            if (animate === false) track.style.transition = 'none';
                            track.style.transform = 'translate3d(-' + (all[i].offsetLeft - base) + 'px, 0px, 0px)';
                            if (animate === false) {
                                void track.offsetWidth; // flush the jump before restoring the transition
                                track.style.transition = '';
                            }
                        }

                        function updateDots() {
                            var active = ((index % count) + count) % count;
                            var dots = dotsWrap.querySelectorAll('.eml-steps-dot');
                            for (var d = 0; d < dots.length; d++) {
                                dots[d].classList.toggle('is-active', d === active);
                            }
                        }

                        var unlock = null;

                        function goTo(i, animate) {
                            index = i;
                            move(index, animate);
                            updateDots();
                            // Safety net: never stay locked if transitionend does not fire.
                            if (unlock) clearTimeout(unlock);
                            unlock = setTimeout(function() {
                                busy = false;
                            }, 900);
                        }

                        function next() {
                            if (busy) return;
                            busy = true;
                            goTo(index + 1);
                        }

                        function prev() {
                            if (busy) return;
                            busy = true;
                            if (index === 0) {
                                // Jump silently to the cloned copy, then animate backwards from there.
                                goTo(count, false);
                                requestAnimationFrame(function() {
                                    requestAnimationFrame(function() {
                                        goTo(count - 1);
                                    });
                                });
                            } else {
                                goTo(index - 1);
                            }
                        }

                        track.addEventListener('transitionend', function(e) {
                            if (e.target !== track || e.propertyName !== 'transform') return;
                            busy = false;
                            if (index >= count) goTo(index - count, false);
                        });

                        function buildDots() {
                            dotsWrap.innerHTML = '';
                            for (var i = 0; i < count; i++) {
                                var dot = document.createElement('button');
                                dot.type = 'button';
                                dot.className = 'eml-steps-dot';
                                dot.setAttribute('aria-label', 'Go to slide ' + (i + 1));
                                (function(target) {
                                    dot.addEventListener('click', function() {
                                        if (busy || target === index % count) return;
                                        busy = true;
                                        goTo(target);
                                        restart();
                                    });
                                })(i);
                                dotsWrap.appendChild(dot);
                            }
                        }

                        function restart() {
                            if (timer) clearInterval(timer);
                            timer = setInterval(next, 4000);
                        }

                        prevBtn.addEventListener('click', function() {
                            prev();
                            restart();
                        });
                        nextBtn.addEventListener('click', function() {
                            next();
                            restart();
                        });

                        root.addEventListener('mouseenter', function() {
                            if (timer) clearInterval(timer);
                        });
                        root.addEventListener('mouseleave', restart);

                        // Touch swipe (mobile).
                        var startX = null;
                        track.addEventListener('touchstart', function(e) {
                            startX = e.touches[0].clientX;
                        }, {
                            passive: true
                        });
                        track.addEventListener('touchend', function(e) {
                            if (startX === null) return;
                            var delta = e.changedTouches[0].clientX - startX;
                            if (Math.abs(delta) > 40) {
                                delta < 0 ? next() : prev();
                                restart();
                            }
                            startX = null;
                        });

                        function recalc() {
                            base = all[0].offsetLeft;
                            goTo(index % count, false);
                        }

                        var resizeTimer = null;
                        window.addEventListener('resize', function() {
                            if (resizeTimer) clearTimeout(resizeTimer);
                            resizeTimer = setTimeout(recalc, 150);
                        });
                        window.addEventListener('load', recalc);

                        buildDots();
                        goTo(0, false);
                        restart();
                    })();
                </script>
